function count(text: string, words: readonly string[]): number {
  let n = 0;
  for (const w of words) {
    if (new RegExp(`(^|[^a-z0-9])${w}([^a-z0-9]|$)`, 'i').test(text)) n++;
  }
  return n;
}

export function classifyScope(question: string): ScopeResult {
  const text = ` ${question.toLowerCase().replace(/\s+/g, ' ')} `;
  const crisis = count(text, CRISIS) > 0;
  const medical = count(text, MEDICAL) > 0;
  const extreme = count(text, EXTREME) > 0;
  const career = count(text, CAREER);
  const health = count(text, HEALTH) + (medical || crisis || extreme ? 1 : 0);
  // A tie goes to health ("sleep better before an exam" is about sleep).
  const scope: Scope =
    crisis || (health > 0 && health >= career) ? 'health' : career > 0 ? 'career' : 'off_topic';
  return { scope, medical, crisis, extreme };
}

